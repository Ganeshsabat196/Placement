#!/usr/bin/env python3
"""Bundle the Markdown notes into assets/content.js for the website.

The Markdown files are the single source of truth. After editing any of them, run:

    python3 build.py

and commit the regenerated assets/content.js.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
FILES = [
    "00_Preparation_Plan.md",
    "01_DS_Concepts_Notes.md",
    "02_DS_Interview_Questions.md",
    "03_DS_Case_Study_Questions.md",
]

content = {name: (ROOT / name).read_text(encoding="utf-8") for name in FILES}

out = ROOT / "assets" / "content.js"
out.parent.mkdir(exist_ok=True)
out.write_text(
    "// Generated by build.py from the Markdown files. Do not edit by hand.\n"
    "window.PREP_CONTENT = " + json.dumps(content, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)
print(f"Wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB) from {len(FILES)} files")
